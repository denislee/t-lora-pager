import json
import os


def _load(project_dir, name):
    path = os.path.join(project_dir, "protocol", "vectors", name)
    with open(path) as f:
        return json.load(f)


def _cstr(s):
    """Emit a C string literal for an already-safe ASCII value."""
    return '"' + s + '"'


def _render_header(project_dir):
    message = _load(project_dir, "message.json")
    segment = _load(project_dir, "segment.json")
    reassemble = _load(project_dir, "reassemble.json")
    bulk = _load(project_dir, "bulk.json")

    out = []
    a = out.append

    a("/* GENERATED by support/gen_link_vectors.py — do not edit */")
    a("#pragma once")
    a("#include <cstdint>")
    a("#include <cstddef>")
    a("")

    # ---- message.json : valid ---------------------------------------------
    a("struct VecMsgValid {")
    a("    const char *name;")
    a("    uint8_t type;")
    a("    uint16_t id;")
    a("    const char *payload_hex;")
    a("    const char *bytes_hex;")
    a("};")
    a("static const VecMsgValid kMsgValid[] = {")
    for v in message["valid"]:
        a("    {%s, %d, %d, %s, %s}," % (
            _cstr(v["name"]), v["type"], v["id"],
            _cstr(v["payload_hex"]), _cstr(v["bytes_hex"])))
    a("};")
    a("static const size_t kMsgValidCount = sizeof(kMsgValid) / sizeof(kMsgValid[0]);")
    a("")

    # ---- message.json : malformed -----------------------------------------
    a("struct VecMsgBad {")
    a("    const char *name;")
    a("    const char *bytes_hex;")
    a("    const char *reason;")
    a("};")
    a("static const VecMsgBad kMsgBad[] = {")
    for v in message["malformed"]:
        a("    {%s, %s, %s}," % (
            _cstr(v["name"]), _cstr(v["bytes_hex"]), _cstr(v["reason"])))
    a("};")
    a("static const size_t kMsgBadCount = sizeof(kMsgBad) / sizeof(kMsgBad[0]);")
    a("")

    # ---- segment.json -----------------------------------------------------
    for i, s in enumerate(segment):
        a("static const char *const kSegPackets_%d[] = {" % i)
        for p in s["packets_hex"]:
            a("    %s," % _cstr(p))
        a("};")
    a("struct VecSegment {")
    a("    const char *name;")
    a("    size_t packet_size;")
    a("    uint8_t start_seq;")
    a("    const char *message_hex;")
    a("    const char *const *packets;")
    a("    size_t n_packets;")
    a("    uint8_t next_seq;")
    a("};")
    a("static const VecSegment kSegment[] = {")
    for i, s in enumerate(segment):
        a("    {%s, %d, %d, %s, kSegPackets_%d, %d, %d}," % (
            _cstr(s["name"]), s["packet_size"], s["start_seq"],
            _cstr(s["message_hex"]), i, len(s["packets_hex"]), s["next_seq"]))
    a("};")
    a("static const size_t kSegmentCount = sizeof(kSegment) / sizeof(kSegment[0]);")
    a("")

    # ---- reassemble.json --------------------------------------------------
    a("struct VecEvent {")
    a("    char kind; /* 'm' message, 'r' reset */")
    a("    const char *text; /* hex or reason */")
    a("};")
    for i, r in enumerate(reassemble):
        pkts = r["packets_hex"]
        if pkts:
            a("static const char *const kReassPkts_%d[] = {" % i)
            for p in pkts:
                a("    %s," % _cstr(p))
            a("};")
        else:
            a("static const char *const kReassPkts_%d[] = {\"\"}; /* dummy, n=0 */" % i)
        events = r["events"]
        if events:
            a("static const VecEvent kReassEvents_%d[] = {" % i)
            for e in events:
                if e["kind"] == "message":
                    a("    {'m', %s}," % _cstr(e["hex"]))
                else:
                    a("    {'r', %s}," % _cstr(e["reason"]))
            a("};")
        else:
            a("static const VecEvent kReassEvents_%d[] = {{'m', \"\"}}; /* dummy, n=0 */" % i)
    a("struct VecReassemble {")
    a("    const char *name;")
    a("    const char *const *packets;")
    a("    size_t n_packets;")
    a("    const VecEvent *events;")
    a("    size_t n_events;")
    a("};")
    a("static const VecReassemble kReassemble[] = {")
    for i, r in enumerate(reassemble):
        a("    {%s, kReassPkts_%d, %d, kReassEvents_%d, %d}," % (
            _cstr(r["name"]), i, len(r["packets_hex"]), i, len(r["events"])))
    a("};")
    a("static const size_t kReassembleCount = sizeof(kReassemble) / sizeof(kReassemble[0]);")
    a("")

    # ---- bulk.json --------------------------------------------------------
    a("struct VecData {")
    a("    uint32_t offset;")
    a("    const char *bytes_hex;")
    a("    const char *payload_hex;")
    a("};")
    a("static const VecData kData[] = {")
    for d in bulk["data"]:
        a("    {%du, %s, %s}," % (d["offset"], _cstr(d["bytes_hex"]),
                                  _cstr(d["payload_hex"])))
    a("};")
    a("static const size_t kDataCount = sizeof(kData) / sizeof(kData[0]);")
    a("")

    a("struct VecAck {")
    a("    uint32_t next;")
    a("    uint16_t credits;")
    a("    const char *payload_hex;")
    a("};")
    a("static const VecAck kAck[] = {")
    for k in bulk["ack"]:
        a("    {%du, %d, %s}," % (k["next"], k["credits"], _cstr(k["payload_hex"])))
    a("};")
    a("static const size_t kAckCount = sizeof(kAck) / sizeof(kAck[0]);")
    a("")

    a("struct VecBad {")
    a("    const char *name;")
    a("    const char *payload_hex;")
    a("};")
    a("static const VecBad kBadData[] = {")
    for b in bulk["bad_data"]:
        a("    {%s, %s}," % (_cstr(b["name"]), _cstr(b["payload_hex"])))
    a("};")
    a("static const size_t kBadDataCount = sizeof(kBadData) / sizeof(kBadData[0]);")
    a("")
    a("static const VecBad kBadAck[] = {")
    for b in bulk["bad_ack"]:
        a("    {%s, %s}," % (_cstr(b["name"]), _cstr(b["payload_hex"])))
    a("};")
    a("static const size_t kBadAckCount = sizeof(kBadAck) / sizeof(kBadAck[0]);")
    a("")

    a("struct VecCrc32 {")
    a("    const char *name;")
    a("    const char *input_hex;")
    a("    uint32_t crc32;")
    a("};")
    a("static const VecCrc32 kCrc32[] = {")
    for c in bulk["crc32"]:
        a("    {%s, %s, 0x%08xu}," % (
            _cstr(c["name"]), _cstr(c["input_hex"]), c["crc32"]))
    a("};")
    a("static const size_t kCrc32Count = sizeof(kCrc32) / sizeof(kCrc32[0]);")
    a("")

    return "\n".join(out)


def _render_settings_header(project_dir):
    """settings.json as one compact raw string for test_settings_registry."""
    text = json.dumps(_load(project_dir, "settings.json"), separators=(",", ":"))
    assert ")VEC\"" not in text
    return "\n".join([
        "/* GENERATED by support/gen_link_vectors.py — do not edit */",
        "#pragma once",
        "static const char kSettingsVectorsJson[] = R\"VEC(" + text + ")VEC\";",
        "",
    ])


def _write_if_changed(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    cur = None
    if os.path.exists(path):
        with open(path) as f:
            cur = f.read()
    if cur == text:
        return False
    with open(path, "w") as f:
        f.write(text)
    return True


def generate(project_dir):
    """Write the generated headers. Returns True when either file changed."""
    a = _write_if_changed(
        os.path.join(project_dir, "test", "test_link_frame", "link_vectors_gen.h"),
        _render_header(project_dir))
    b = _write_if_changed(
        os.path.join(project_dir, "test", "test_settings_registry", "settings_vectors_gen.h"),
        _render_settings_header(project_dir))
    return a or b


if __name__ == "__main__":
    generate(_PROJECT_DIR)
    print("wrote test/test_link_frame/link_vectors_gen.h and "
          "test/test_settings_registry/settings_vectors_gen.h")
else:
    # PlatformIO pre-script: generate during build configuration.
    generate(_PROJECT_DIR)
